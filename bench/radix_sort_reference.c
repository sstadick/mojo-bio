#include <assert.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

typedef struct {
    uint64_t key;
    uint64_t payload;
} record_t;

#define RS_MIN_SIZE 64
#define RS_MAX_BITS 8
#define record_key(r) ((r).key)

typedef struct {
    record_t *b, *e;
} rsbucket_record_t;

void rs_insertsort_record(record_t *beg, record_t *end) {
    record_t *i;
    for (i = beg + 1; i < end; ++i) {
        if (record_key(*i) < record_key(*(i - 1))) {
            record_t *j, tmp = *i;
            for (j = i; j > beg && record_key(tmp) < record_key(*(j - 1)); --j) *j = *(j - 1);
            *j = tmp;
        }
    }
}

void rs_sort_record(record_t *beg, record_t *end, int n_bits, int s) {
    record_t *i;
    int size = 1 << n_bits, m = size - 1;
    rsbucket_record_t *k, buckets[1 << RS_MAX_BITS], *be = buckets + size;
    assert(n_bits <= RS_MAX_BITS);
    for (k = buckets; k != be; ++k) k->b = k->e = beg;
    for (i = beg; i != end; ++i) ++buckets[(record_key(*i) >> s) & m].e;
    for (k = buckets + 1; k != be; ++k) {
        k->e += (k - 1)->e - beg;
        k->b = (k - 1)->e;
    }
    for (k = buckets; k != be;) {
        if (k->b != k->e) {
            rsbucket_record_t *l;
            if ((l = buckets + ((record_key(*k->b) >> s) & m)) != k) {
                record_t tmp = *k->b, swap;
                do {
                    swap = tmp;
                    tmp = *l->b;
                    *l->b++ = swap;
                    l = buckets + ((record_key(tmp) >> s) & m);
                } while (l != k);
                *k->b++ = tmp;
            } else {
                ++k->b;
            }
        } else {
            ++k;
        }
    }
    for (buckets->b = beg, k = buckets + 1; k != be; ++k) k->b = (k - 1)->e;
    if (s) {
        s = s > n_bits ? s - n_bits : 0;
        for (k = buckets; k != be; ++k) {
            if (k->e - k->b > RS_MIN_SIZE) rs_sort_record(k->b, k->e, n_bits, s);
            else if (k->e - k->b > 1) rs_insertsort_record(k->b, k->e);
        }
    }
}

static record_t *source;
static record_t *work;
static int64_t record_count;

static uint64_t next_random(uint64_t *state) {
    uint64_t x = *state;
    x ^= x << 13;
    x ^= x >> 7;
    x ^= x << 17;
    return *state = x;
}

void c_setup(int64_t len) {
    free(source);
    free(work);
    record_count = len;
    source = malloc((size_t)len * sizeof(*source));
    work = malloc((size_t)len * sizeof(*work));
    if (!source || !work) abort();
    uint64_t state = UINT64_C(0x4D595DF4D0F33173);
    for (int64_t i = 0; i < len; ++i) {
        uint64_t key = next_random(&state);
        source[i] = (record_t){key, key ^ UINT64_C(0x9E3779B97F4A7C15)};
    }
}

void c_reset(void) {
    memcpy(work, source, (size_t)record_count * sizeof(*work));
}

/* Same entry point generated by KRADIX_SORT_INIT in cgranges.c. */
void c_radix_sort(void) {
    record_t *end = work + record_count;
    if (record_count <= RS_MIN_SIZE) rs_insertsort_record(work, end);
    else rs_sort_record(work, end, RS_MAX_BITS, 56);
}

bool c_validate(void) {
    for (int64_t i = 1; i < record_count; ++i) {
        if (work[i - 1].key > work[i].key) return false;
    }
    return true;
}

uint64_t c_checksum(void) {
    return work[0].key ^ work[record_count / 2].payload ^ work[record_count - 1].key;
}

void c_teardown(void) {
    free(source);
    free(work);
    source = NULL;
    work = NULL;
    record_count = 0;
}
